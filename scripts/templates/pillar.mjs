const tabs = (pillar, programs) => {
  const list = pillar.tabs.map((id) => programs.find((p) => p.id === id));
  return `
    <section class="section" id="capabilities">
      <div class="container">
        <div class="section-head reveal">
          <span class="eyebrow">Capabilities</span>
          <h2 class="h2">${esc(pillar.tabsTitle)}</h2>
        </div>
        <div class="tabs reveal" data-tabs>
          <div class="tablist" role="tablist" aria-label="Capabilities">
            ${list.map((p, i) => `<button role="tab" id="tab-${p.slug}" aria-controls="panel-${p.slug}" aria-selected="${i === 0}" tabindex="${i === 0 ? 0 : -1}">${icon(p.icon)}${esc(p.title.replace('Real-Time ', ''))}</button>`).join('\n            ')}
          </div>
          ${list.map((p, i) => `
          <div class="tabpanel" role="tabpanel" id="panel-${p.slug}" aria-labelledby="tab-${p.slug}"${i ? ' hidden' : ''}>
            <div class="tab-copy">
              <span class="pcard-kicker"><span class="mono">${p.id}</span>·<span>${esc(p.capabilityLabel)}</span></span>
              <h3 class="h3">${esc(p.title)}</h3>
              <p>${esc(p.desc)}</p>
              <ul class="outcomes">${p.outcomes.map((o) => `<li>${icon('check')}${esc(o)}</li>`).join('')}</ul>
              <div class="tags">${p.chips.map((c) => `<span class="tag">${esc(c)}</span>`).join('')}</div>
              <div class="sc-actions">${pilotCta(p, 'Request a pilot', 'btn btn-primary btn-md')}<a class="btn btn-secondary btn-md" href="/programs/${p.slug}">View program ${icon('arrow-up-right', 'ic-sm go')}</a></div>
            </div>
            ${frame(p)}
          </div>`).join('')}
        </div>
      </div>
    </section>`;
};

