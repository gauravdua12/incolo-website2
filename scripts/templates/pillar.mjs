const cards = (eyebrow, title, items, id) => `
    <section class="section" id="${id}">
      <div class="container">
        <div class="section-head reveal"><span class="eyebrow">${eyebrow}</span><h2 class="h2">${esc(title)}</h2></div>
        <div class="gov-grid reveal">
          ${items.map(([ic, h, p]) => `<article class="gov-card">${tile(ic)}<h3>${esc(h)}</h3><p>${esc(p)}</p></article>`).join('\n          ')}
        </div>
      </div>
    </section>`;

export function pillarPage(pillar, pillars, programs) {
  const related = pillar.relatedAll ? programs : programs.filter((p) => p.pillar === pillar.slug);
  const others = pillars.filter((p) => p.slug !== pillar.slug);
  const navItems = [['overview', 'Overview']];
  if (pillar.tabs) navItems.push(['capabilities', 'Capabilities']);
  if (pillar.phases) navItems.push(['engagement', 'Engagement']);
  if (pillar.principles) navItems.push(['principles', 'How we work']);
  navItems.push(['architecture', 'Architecture'], ['deployment', 'Data residency'], ['governance', 'Governance'], ['programs', 'Programs']);

  return `  <main id="main" class="pillar-page">
    <div class="subnav" id="subnav">
      <div class="container subnav-inner">
        <span class="chip"><span class="chip-ic"><svg><use href="/media/icons.svg#${pillar.icon}"/></svg></span>${esc(pillar.name)}</span>
        <nav aria-label="On this page">${navItems.map(([id, l], i) => `<a href="#${id}"${i === 0 ? ' class="on"' : ''}>${l}</a>`).join('')}</nav>
        <a class="btn btn-primary subnav-cta" href="/contact" data-open-modal>Book a scoping call</a>
      </div>
    </div>

    <section class="hero pillar-hero" id="overview">
      <div class="netbg" aria-hidden="true"><span class="glow"></span><svg class="lines" data-net="pillar"></svg></div>
      <div class="container hero-inner">
        <span class="chip"><span class="chip-ic"><svg><use href="/media/icons.svg#${pillar.icon}"/></svg></span>${esc(pillar.name)}</span>
        <h1 class="h1">${esc(pillar.h1)}</h1>
        <p class="lede">${esc(pillar.sub)}</p>
        <div class="hero-actions">
          <a class="btn btn-primary btn-lg" href="/contact" data-open-modal>Book a scoping call</a>
          <a class="btn btn-secondary btn-lg" href="#programs">Browse programs</a>
        </div>
        <div class="hero-frame reveal">
          ${frame(pillar, { tall: true })}
          ${pillar.callouts.map((c, i) => `<span class="callout c${i + 1}"><span class="dot" aria-hidden="true"></span>${esc(c)}</span>`).join('\n          ')}
        </div>
      </div>
    </section>

    <section class="container">
      <div class="stats reveal">
        ${pillar.stats.map(([k, v]) => `<div class="stat"><div class="k">${esc(k)}</div><div class="v">${esc(v)}</div></div>`).join('\n        ')}
      </div>
    </section>
${pillar.tabs ? tabs(pillar, programs) : ''}${pillar.featured ? featured(programs.find((p) => p.id === pillar.featured)) : ''}${pillar.phases ? phases('Three phases. Quality gates at every step.') : ''}${pillar.principles ? cards('How we work', pillar.principlesTitle, pillar.principles, 'principles') : ''}${architecture()}${residency('Deployed where you decide.')}${cards('Trust by design', 'Validated before scaled.', pillar.governance, 'governance')}
    <section class="section" id="programs">
      <div class="container">
        <div class="section-head reveal">
          <span class="eyebrow">Programs</span>
          <h2 class="h2">${pillar.relatedAll ? 'Programs we take from feasibility to rollout.' : 'Programs in this solution.'}</h2>
        </div>
        <div class="mini-grid reveal">${related.map(miniCard).join('')}
        </div>
        <p class="center" style="margin-top:28px"><a class="link-arrow" href="/programs">See all programs ${icon('arrow-right')}</a></p>
      </div>
    </section>

    <section class="section" style="padding-top:0">
      <div class="container">
        <div class="section-head reveal"><span class="eyebrow">Other solutions</span><h2 class="h2">Explore the rest of the platform.</h2></div>
        <div class="other-grid reveal">
          ${others.map((o) => `<a class="other-card" href="/solutions/${o.slug}">${tile(o.icon)}<span><strong>${esc(o.name)}</strong><span>${esc(o.short)}</span></span><span class="btn btn-secondary">Explore ${icon('arrow-up-right', 'ic-sm go')}</span></a>`).join('\n          ')}
        </div>
      </div>
    </section>

${finalCta}
  </main>`;
}
